// NtcSceneControllerEditor.cs
// Custom Inspector for NtcSceneController. The default Inspector is very noisy: the
// MaterialGroup class has 5 Texture2D fields per entry (ntcColor/Normal/Metalness/AO/
// Smoothness), which are ONLY ever filled at runtime and are meaningless to hand-edit --
// with 17 materials that's 85 texture picker fields with nothing useful in them in Edit
// mode. This custom editor replaces that with a compact read-only summary + a Rescan
// button, and only exposes the handful of fields that are actually meant to be tweaked.
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;
using UnityEngine.SceneManagement;

namespace Ntc.Unity
{
    [CustomEditor(typeof(NtcSceneController))]
    public class NtcSceneControllerEditor : Editor
    {
        bool _showRawGroups;

        public override void OnInspectorGUI()
        {
            var ctrl = (NtcSceneController)target;

            EditorGUILayout.HelpBox(
                "This component switches ALL renderers in the open scene between 3 modes at " +
                "runtime (Original / on-Load / on-Sample) and shows a debug panel while playing.\n\n" +
                "Fields you actually need to touch: Mode (default mode on Play), On Sample Shader " +
                "(usually auto-found), Ntc Data Path (only if you moved the Bake output folder), " +
                "and the UI toggle key.\n\n" +
                "'Material Groups' below is auto-generated by scanning the scene -- do not hand-edit it, " +
                "use the Rescan button instead.",
                MessageType.Info);

            EditorGUILayout.Space();
            serializedObject.Update();

            EditorGUILayout.PropertyField(serializedObject.FindProperty("mode"));
            EditorGUILayout.PropertyField(serializedObject.FindProperty("onSampleShader"));
            EditorGUILayout.PropertyField(serializedObject.FindProperty("onLoadSwapAllMaps"));
            EditorGUILayout.PropertyField(serializedObject.FindProperty("ntcDataPath"));
            EditorGUILayout.PropertyField(serializedObject.FindProperty("ntcFilePrefix"));

            EditorGUILayout.Space();
            EditorGUILayout.LabelField("Debug panel (while playing)", EditorStyles.boldLabel);
            EditorGUILayout.PropertyField(serializedObject.FindProperty("showPanel"));
            EditorGUILayout.PropertyField(serializedObject.FindProperty("togglePanelKey"));

            serializedObject.ApplyModifiedProperties();

            EditorGUILayout.Space();
            EditorGUILayout.LabelField("Material Groups (auto-scanned, read-only summary)", EditorStyles.boldLabel);

            NtcSceneController.MaterialGroup[] groups = ctrl.groups;
            int count = groups != null ? groups.Length : 0;

            EditorGUILayout.BeginHorizontal();
            if (GUILayout.Button("Rescan Scene Materials", GUILayout.Height(24)))
            {
                Undo.RecordObject(ctrl, "Rescan NTC Scene Materials");
                ctrl.ScanSceneMaterials();
                EditorUtility.SetDirty(ctrl);
                if (!Application.isPlaying)
                    EditorSceneManager.MarkSceneDirty(SceneManager.GetActiveScene());
            }
            if (GUILayout.Button("Open Bake Window", GUILayout.Height(24), GUILayout.Width(140)))
            {
                EditorApplication.ExecuteMenuItem("NTC/Bake Window");
            }
            EditorGUILayout.EndHorizontal();

            if (count == 0)
            {
                EditorGUILayout.HelpBox(
                    "No material groups yet. Open the scene you want to test, then click " +
                    "'Rescan Scene Materials' above (or the NTC/Add Scene Controller menu the first time).",
                    MessageType.Warning);
                return;
            }

            EditorGUILayout.LabelField(count + " material(s) found in the open scene:", EditorStyles.miniBoldLabel);
            for (int i = 0; i < count; i++)
            {
                NtcSceneController.MaterialGroup g = groups[i];
                if (g == null) continue;
                int rendererCount = g.renderers != null ? g.renderers.Length : 0;
                string ntcInfo = string.IsNullOrEmpty(g.ntcFilePath) ? "not baked yet" : g.ntcFilePath;

                EditorGUILayout.BeginHorizontal("box");
                EditorGUILayout.LabelField(g.name, GUILayout.Width(160));
                EditorGUILayout.LabelField(rendererCount + " renderer(s)", GUILayout.Width(90));
                EditorGUILayout.LabelField(ntcInfo, EditorStyles.miniLabel);
                EditorGUILayout.EndHorizontal();
            }

            EditorGUILayout.Space();
            _showRawGroups = EditorGUILayout.Foldout(_showRawGroups, "Advanced: raw serialized array (rarely needed)");
            if (_showRawGroups)
            {
                EditorGUILayout.HelpBox(
                    "Manual editing here is only needed to fix a mis-detected renderer/material " +
                    "mapping. Texture fields below are populated by Play mode and are not meant " +
                    "to be assigned by hand.",
                    MessageType.None);
                EditorGUILayout.PropertyField(serializedObject.FindProperty("groups"), true);
                serializedObject.ApplyModifiedProperties();
            }
        }
    }
}
